"""The abstraction that hides whether sampling happens in-process or across Ray."""

from __future__ import annotations

from abc import ABC, abstractmethod

import numpy as np

from ..primitives import EpisodeResult, Segment


class RolloutEngine(ABC):
    """Three methods, and everything distribution-related lives behind them."""

    @abstractmethod
    def sync_weights(self, actor_state_dict: dict[str, np.ndarray]) -> None:
        """Push the learner's current inference weights to every agent replica.

        At ~20 KB for this project's policies, a broadcast costs microseconds.
        That is what lets on-policy algorithms here be exactly on-policy:
        every frame in an iteration generated by the precise weights about to
        be updated, rather than accepting policy lag and correcting for it.
        """

    @abstractmethod
    def collect(self, n_frames: int) -> tuple[Segment, list[EpisodeResult]]:
        """Collect exactly n_frames agent steps and the episodes that finished."""

    @abstractmethod
    def close(self) -> None:
        """Release environments and any worker processes."""
